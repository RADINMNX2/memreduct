const dicts: Record<Lang, typeof en> = { en, fa };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let val: unknown = key.split('.').reduce((acc: unknown, k) => {
    if (acc && typeof acc === 'object') return (acc as Record<string, unknown>)[k];
    return undefined;
  }, dicts[lang] || en);
  if (val === undefined) {
    val = key.split('.').reduce((acc: unknown, k) => {
      if (acc && typeof acc === 'object') return (acc as Record<string, unknown>)[k];
      return undefined;
    }, en);
  }
  let str = String(val ?? key);
  if (vars) {
    for (const k of Object.keys(vars)) str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
  }
  return str;
}

